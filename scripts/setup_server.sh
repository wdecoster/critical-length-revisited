#!/usr/bin/env bash
# Set up a server: the snakemake env, the workflow envs, the GRCh38 reference, and config/server.yaml +
# profiles/server/config.yaml (both not in git). Everything else (truth sets, stratifications, assemblies,
# reads) is downloaded by the workflow, under the output root. Run from anywhere.
#
# Usage: scripts/setup_server.sh [-o DIR] [-d DIR] [-r FASTA] [-n]
#   -o, --output-root DIR   results and downloaded resources (e.g. a study folder; default: <repo>)
#   -d, --dest DIR          conda envs, containers, a downloaded reference (default: <repo>/resources)
#   -r, --reference FASTA   an existing GRCh38 no-alt analysis set (with .fai); downloaded if not given
#   -n, --dry-run           print the commands instead of running them
#
# Afterwards:
#   mamba activate critical-length-revisited
#   snakemake --configfile config/server.yaml --profile profiles/server -n
set -euo pipefail

repo=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
dest="$repo/resources"
reference=""
output_root=""
dry_run=false
while [ $# -gt 0 ]; do
    case "$1" in
        -d|--dest) dest=$2; shift 2 ;;
        -r|--reference) reference=$2; shift 2 ;;
        -o|--output-root) output_root=$2; shift 2 ;;
        -n|--dry-run) dry_run=true; shift ;;
        -h|--help) sed -n '2,15p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "Unknown argument: $1" >&2; exit 1 ;;
    esac
done
mkdir -p "$dest"
dest=$(cd "$dest" && pwd)
conda_envs="$dest/conda-envs"
containers="$dest/containers"

run() {
    echo "+ $*"
    if ! $dry_run; then eval "$@"; fi
}

if command -v mamba > /dev/null; then conda=mamba
elif command -v conda > /dev/null; then conda=conda
else echo "conda/mamba not found: install Miniforge first" >&2; exit 1; fi

# mamba 2 indents environment names in 'env list'
if ! $conda env list | awk '{print $1}' | grep -qx critical-length-revisited; then
    run "$conda env create -y -f '$repo/envs/snakemake.yaml'"
fi

if [ -z "$reference" ]; then
    reference="$dest/reference/GCA_000001405.15_GRCh38_no_alt_analysis_set.fna"
    if [ ! -s "$reference" ]; then
        run "mkdir -p '$dest/reference'"
        run "curl -sSfL https://ftp.ncbi.nlm.nih.gov/genomes/all/GCA/000/001/405/GCA_000001405.15_GRCh38/seqs_for_alignment_pipelines.ucsc_ids/GCA_000001405.15_GRCh38_no_alt_analysis_set.fna.gz | gzip -dc > '$reference'"
    fi
fi
[ -s "$reference.fai" ] || run "$conda run -n critical-length-revisited samtools faidx '$reference'"

[ -n "$output_root" ] && run "mkdir -p '$output_root'"
output_root=$(realpath -ms "${output_root:-$repo}")

# containers see only bound paths: bind the top-level directory of every path the workflow uses and its
# resolved location (a symlink into another mount, like a study folder on a different NFS share, is not
# followed inside the container otherwise)
binds=""
for p in "$output_root" "$(dirname "$reference")" "$dest" "$repo"; do
    p=$(realpath -ms "$p")  # as given (no symlinks resolved), plus its resolved location
    for b in "/$(echo "$p" | cut -d/ -f2)" "$(readlink -f "$p" || echo "$p")"; do
        case " $binds " in *" -B $b "*) ;; *) binds="$binds -B $b" ;; esac
    done
done

if ! $dry_run; then
    cat > "$repo/config/server.yaml" <<EOF
# Generated by scripts/setup_server.sh
reference: $reference
output_root: $output_root
EOF
    mkdir -p "$repo/profiles/server"
    cat > "$repo/profiles/server/config.yaml" <<EOF
# Generated by scripts/setup_server.sh; combined with workflow/profiles/default
conda-prefix: $conda_envs
apptainer-prefix: $containers
apptainer-args: "${binds# }"
EOF
    echo "wrote config/server.yaml and profiles/server/config.yaml"
fi

# build the workflow conda envs now rather than in the first run
run "cd '$repo' && $conda run -n critical-length-revisited snakemake --configfile config/server.yaml --profile profiles/server --conda-create-envs-only --cores 1"
